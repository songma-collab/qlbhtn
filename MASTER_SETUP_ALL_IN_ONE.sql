      AND COALESCE(status, 'Đang hoạt động') != 'Tạm khóa'
  );
END;
$$;

-- 1.5. Hàm lấy mã định danh cán bộ thu hiện tại (current_staff_id)
CREATE OR REPLACE FUNCTION public.current_staff_id()
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
STABLE
AS $$
DECLARE
  v_uid UUID := auth.uid();
  v_email TEXT := LOWER(TRIM(COALESCE(auth.jwt() ->> 'email', '')));
  v_id TEXT;
BEGIN
  IF v_uid IS NULL THEN
    RETURN NULL;
  END IF;

  SELECT id INTO v_id 
  FROM public.staff 
  WHERE auth_user_id = v_uid 
    AND COALESCE(status, 'Đang hoạt động') != 'Tạm khóa'
  LIMIT 1;

  IF v_id IS NOT NULL THEN
    RETURN v_id;
  END IF;

  IF v_email != '' THEN
    SELECT id INTO v_id 
    FROM public.staff 
    WHERE LOWER(TRIM(email)) = v_email 
      AND COALESCE(status, 'Đang hoạt động') != 'Tạm khóa'
    LIMIT 1;
    RETURN v_id;
  END IF;

  RETURN NULL;
END;
$$;

-- 1.6. Hàm truy vấn vai trò người dùng (get_my_role)
CREATE OR REPLACE FUNCTION public.get_my_role()
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_role TEXT;
BEGIN
  -- Ưu tiên 1: Tra cứu theo auth.uid()
  IF auth.uid() IS NOT NULL THEN
    SELECT 
      CASE 
        WHEN lower(role) = 'admin' THEN 'Admin'
        WHEN lower(role) = 'quản lý' THEN 'Quản lý'
        ELSE role
      END INTO v_role
    FROM public.staff 
    WHERE auth_user_id = auth.uid() 
      AND status != 'Tạm khóa'
    LIMIT 1;

    IF v_role IS NOT NULL THEN
      RETURN v_role;
    END IF;
  END IF;

  -- Ưu tiên 2: Fallback tra cứu qua JWT email
  IF auth.jwt()->>'email' IS NOT NULL THEN
    SELECT 
      CASE 
        WHEN lower(role) = 'admin' THEN 'Admin'
        WHEN lower(role) = 'quản lý' THEN 'Quản lý'
        ELSE role
      END INTO v_role
    FROM public.staff 
    WHERE lower(email) = lower(auth.jwt()->>'email')
      AND status != 'Tạm khóa'
    LIMIT 1;

    IF v_role IS NOT NULL THEN
      RETURN v_role;
    END IF;
  END IF;

  RETURN 'anon';
END;
$$;

