-- 2.7.2c. Hàm truy vấn vai trò người dùng (get_my_role)
CREATE OR REPLACE FUNCTION public.get_my_role()
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_role text;
BEGIN
  -- 1. Ưu tiên tra cứu theo auth.uid()
  IF auth.uid() IS NOT NULL THEN
    SELECT 
      CASE 
        WHEN lower(role) = 'admin' THEN 'Admin'
        WHEN lower(role) = 'quản lý' THEN 'Quản lý'
        ELSE role
      END INTO v_role
    FROM public.staff 
    WHERE auth_user_id = auth.uid() 
      AND status != 'Tạm khóa'
    LIMIT 1;

    IF v_role IS NOT NULL THEN
      RETURN v_role;
    END IF;
  END IF;

  -- 2. Fallback tra cứu qua JWT email (dành cho giai đoạn chuyển tiếp)
  IF auth.jwt()->>'email' IS NOT NULL THEN
    SELECT 
      CASE 
        WHEN lower(role) = 'admin' THEN 'Admin'
        WHEN lower(role) = 'quản lý' THEN 'Quản lý'
        ELSE role
      END INTO v_role
    FROM public.staff 
    WHERE lower(email) = lower(auth.jwt()->>'email')
      AND status != 'Tạm khóa'
    LIMIT 1;

    IF v_role IS NOT NULL THEN
      RETURN v_role;
    END IF;
  END IF;

  RETURN 'anon';
END;
$$;

