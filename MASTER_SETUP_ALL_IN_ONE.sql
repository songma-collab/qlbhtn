-- 7.10. RPC Tra cứu hồ sơ khách hàng tự động điền (lookup_customer_profile)
-- Ưu tiên tra cứu từ Bảng Khách hàng gốc (customers Master Table), sau đó fallback bảng Giao dịch (records)
DROP FUNCTION IF EXISTS public.lookup_customer_profile(TEXT) CASCADE;
DROP FUNCTION IF EXISTS public.lookup_customer_profile CASCADE;
CREATE OR REPLACE FUNCTION public.lookup_customer_profile(p_code TEXT)
RETURNS TABLE (
  name TEXT,
  cccd TEXT,
  phone TEXT,
  bhxh TEXT,
  old_bhxh TEXT,
  dob DATE,
  gender TEXT,
  nation TEXT,
  email TEXT,
  address TEXT,
  income NUMERIC,
  method TEXT,
  "nnSupportPct" NUMERIC,
  "dpSupportPct" NUMERIC,
  notes TEXT
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_clean TEXT;
BEGIN
  -- Chỉ nhân viên đã đăng nhập hoặc service_role mới được tra cứu toàn bộ PII
  IF auth.role() NOT IN ('service_role', 'authenticated') THEN
    RAISE EXCEPTION 'Access denied: Quyền tra cứu thông tin khách hàng chỉ dành cho nhân viên đã đăng nhập hệ thống.'
      USING ERRCODE = '42501';
  END IF;

  v_clean := REGEXP_REPLACE(COALESCE(p_code, ''), '\D', '', 'g');
  IF v_clean !~ '^\d{9}$|^\d{10}$|^\d{12}$' THEN
    RETURN;
  END IF;

  -- 1. Ưu tiên tra cứu trực tiếp từ bảng Master Customers
  RETURN QUERY
  SELECT 
    c.name,
    c.cccd,
    c.phone,
    c.bhxh,
    COALESCE(c.old_bhxh, (CASE WHEN LENGTH(c.bhxh) = 10 THEN c.bhxh ELSE '' END)) AS old_bhxh,
    c.dob,
    COALESCE(c.gender, 'Nam') AS gender,
    COALESCE(c.nation, 'Kinh') AS nation,
    c.email,
    c.address,
    r.income,
    r.method,
    r."nnSupportPct",
    r."dpSupportPct",
    COALESCE(c.notes, r.notes) AS notes
  FROM public.customers c
  LEFT JOIN public.records r ON c.latest_record_id = r.id
  WHERE (
      (c.cccd = v_clean) OR
      (c.bhxh = v_clean) OR
      (c.old_bhxh = v_clean)
  )
  ORDER BY c.updated_at DESC
  LIMIT 1;

  IF FOUND THEN
    RETURN;
  END IF;

  -- 2. Fallback tìm kiếm trong bảng records nếu customers chưa kịp đồng bộ
  RETURN QUERY
  SELECT 
    r.name,
    r.cccd,
    r.phone,
    r.bhxh,
    COALESCE(r.old_bhxh, (CASE WHEN LENGTH(r.bhxh) = 10 THEN r.bhxh ELSE '' END)) AS old_bhxh,
    r.dob,
    COALESCE(r.gender, 'Nam') AS gender,
    COALESCE(r.nation, 'Kinh') AS nation,
    r.email,
    r.address,
    r.income,
    r.method,
    r."nnSupportPct",
    r."dpSupportPct",
    r.notes
  FROM public.records r
  WHERE r."paymentStatus" != 'Đã hủy'
    AND (
      (r.bhxh = v_clean AND r.bhxh IS NOT NULL AND r.bhxh != '') OR 
      (r.cccd = v_clean AND r.cccd IS NOT NULL AND r.cccd != '') OR
      (r.old_bhxh = v_clean AND r.old_bhxh IS NOT NULL AND r.old_bhxh != '')
    )
  ORDER BY r.date DESC
  LIMIT 1;
END;
$$;

