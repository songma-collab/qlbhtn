      (
        SELECT MAX(r_sub.id) 
        FROM public.records r_sub 
        WHERE ((c.customer_key IS NOT NULL AND r_sub.customer_key = c.customer_key) 
            OR (c.cccd IS NOT NULL AND TRIM(c.cccd) != '' AND r_sub.cccd = c.cccd) 
