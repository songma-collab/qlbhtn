CREATE OR REPLACE FUNCTION public.log_customer_contact(
    p_record_id BIGINT,
    p_note TEXT,
    p_channel TEXT DEFAULT 'Trực tiếp'
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
