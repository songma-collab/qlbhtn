    r.dob,
    r.gender,
    r.nation,
    r.email,
    r.address,
    r.type,
    r.method,
    r.months,
    r.income,
    r.from_month,
    r.to_month,
    r.notes,
    r.recv_name,
    r.recv_phone,
    r.recv_address,
    r.members
  FROM public.records r
  WHERE r.payment_status != 'Đã hủy'
    AND r.type = UPPER(TRIM(p_type))
    AND (
      (r.bhxh = TRIM(p_code) AND r.bhxh IS NOT NULL AND r.bhxh != '') OR 
      (r.cccd = TRIM(p_code) AND r.cccd IS NOT NULL AND r.cccd != '')
    )
