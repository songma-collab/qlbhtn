    is_submitted_bhxh, submission_batch, submitted_date, refund_type,
    decision_number, decision_date, refund_method, refund_beneficiary_name,
    refund_beneficiary_account, refund_beneficiary_bank, is_adjustment,
    original_record_id, adjustment_reason, customer_key, customer_id
  ) VALUES (
    v_orig.name,
    v_orig.cccd,
    v_orig.phone,
    v_orig.address,
    v_orig.bhxh,
    v_orig.old_bhxh,
    v_orig.dob,
    v_orig.gender,
    v_orig.nation,
    v_orig.email,
    v_orig.type,
    v_orig.sub_type,
    'Thoái thu',
    'Hoàn tất thoái thu',
    'Đã thu tiền',
    NOW(),
    v_effective_date,
    v_orig.target_date,
    v_orig.next_payment,
    v_orig.from_month,
    v_orig.to_month,
    v_orig.wage,
    v_orig.income,
    0,
    v_orig.method,
    -1 * ABS(COALESCE(v_orig.base_premium, 0)),
