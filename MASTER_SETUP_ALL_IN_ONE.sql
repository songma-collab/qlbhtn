-- Dọn dẹp bản ghi thừa trùng lặp email nếu có (giữ lại bản ghi chính)
DELETE FROM public.staff a USING public.staff b
WHERE a.id = 'admin-hocsongma' AND b.id != 'admin-hocsongma' AND LOWER(TRIM(a.email)) = LOWER(TRIM(b.email));

-- Tự động liên kết auth_user_id nếu email khớp với tài khoản trong auth.users
UPDATE public.staff s
SET auth_user_id = u.id, role = 'Admin', status = 'Đang hoạt động'
FROM auth.users u
WHERE LOWER(TRIM(s.email)) = LOWER(TRIM(u.email))
  AND (s.auth_user_id IS NULL OR s.auth_user_id != u.id);

