-- 11.3. Đồng bộ 2 chiều dữ liệu cột old_bhxh <-> "oldBhxh"
DO $$
BEGIN
    PERFORM set_config('app.is_admin_override', 'true', true);
    PERFORM set_config('app.is_batch_import', 'true', true);

    -- 11.1. Đảm bảo cả hai cột old_bhxh và "oldBhxh" tồn tại trên bảng records
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' AND table_name = 'records' AND column_name = 'old_bhxh'
    ) THEN
        ALTER TABLE public.records ADD COLUMN "old_bhxh" TEXT;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' AND table_name = 'records' AND column_name = 'oldBhxh'
    ) THEN
        ALTER TABLE public.records ADD COLUMN "oldBhxh" TEXT;
    END IF;

    -- Đồng bộ dữ liệu 2 chiều trên records
    EXECUTE '
        UPDATE public.records 
        SET old_bhxh = COALESCE(NULLIF(TRIM(old_bhxh), ''''), NULLIF(TRIM("oldBhxh"), '''')),
            "oldBhxh" = COALESCE(NULLIF(TRIM("oldBhxh"), ''''), NULLIF(TRIM(old_bhxh), ''''))
        WHERE (old_bhxh IS DISTINCT FROM "oldBhxh")
          AND (old_bhxh IS NOT NULL OR "oldBhxh" IS NOT NULL);
    ';

    -- 11.2. Đảm bảo cả hai cột old_bhxh và "oldBhxh" tồn tại trên bảng customers
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' AND table_name = 'customers' AND column_name = 'old_bhxh'
    ) THEN
        ALTER TABLE public.customers ADD COLUMN "old_bhxh" TEXT;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' AND table_name = 'customers' AND column_name = 'oldBhxh'
    ) THEN
        ALTER TABLE public.customers ADD COLUMN "oldBhxh" TEXT;
    END IF;

    -- Đồng bộ dữ liệu 2 chiều trên customers
    EXECUTE '
        UPDATE public.customers 
        SET old_bhxh = COALESCE(NULLIF(TRIM(old_bhxh), ''''), NULLIF(TRIM("oldBhxh"), '''')),
            "oldBhxh" = COALESCE(NULLIF(TRIM("oldBhxh"), ''''), NULLIF(TRIM(old_bhxh), ''''))
        WHERE (old_bhxh IS DISTINCT FROM "oldBhxh")
          AND (old_bhxh IS NOT NULL OR "oldBhxh" IS NOT NULL);
    ';
    
    RAISE NOTICE 'Đã đồng bộ 2 chiều toàn vẹn các trường old_bhxh / oldBhxh trên records và customers';
END $$;

-- 11.4. Dọn dẹp và chuẩn hóa dữ liệu định danh khách hàng cũ sang mã CUST_...
DO $$
BEGIN
    -- Bật override để tránh trigger khóa kỳ hoặc bảo vệ hồ sơ đã nộp chặn script migration
    PERFORM set_config('app.is_admin_override', 'true', true);
    PERFORM set_config('app.is_batch_import', 'true', true);

    -- 13.1. Hợp nhất dữ liệu tài chính từ khóa cũ sang khóa chuẩn CUST_... nếu còn tồn tại
    UPDATE public.customers new_c
    SET 
        total_contributions = GREATEST(new_c.total_contributions, old_c.total_contributions),
        total_amount_paid = GREATEST(new_c.total_amount_paid, old_c.total_amount_paid),
        old_bhxh = COALESCE(new_c.old_bhxh, old_c.old_bhxh),
        address = COALESCE(new_c.address, old_c.address),
        dob = COALESCE(new_c.dob, old_c.dob),
        gender = COALESCE(new_c.gender, old_c.gender),
        status = CASE 
            WHEN new_c.status = 'Đã dừng đóng' OR old_c.status = 'Đã dừng đóng' THEN 'Đã dừng đóng'
            ELSE COALESCE(new_c.status, old_c.status, 'Đang tham gia')
        END,
        updated_at = NOW()
    FROM public.customers old_c
    WHERE (old_c.customer_key LIKE 'BHXH_%' OR old_c.customer_key LIKE 'BHYT_%')
      AND new_c.customer_key LIKE 'CUST_%'
      AND new_c.id != old_c.id
      AND (
        (new_c.cccd IS NOT NULL AND TRIM(new_c.cccd) != '' AND new_c.cccd = old_c.cccd)
        OR
        (new_c.bhxh IS NOT NULL AND TRIM(new_c.bhxh) != '' AND new_c.bhxh = old_c.bhxh)
      );

    -- 13.2. Xóa các bản ghi thừa mang khóa cũ đã được hợp nhất sang CUST_...
    DELETE FROM public.customers old_c
    WHERE (old_c.customer_key LIKE 'BHXH_%' OR old_c.customer_key LIKE 'BHYT_%')
      AND EXISTS (
          SELECT 1 FROM public.customers new_c
          WHERE new_c.id != old_c.id
            AND new_c.customer_key LIKE 'CUST_%'
            AND (
              (new_c.cccd IS NOT NULL AND TRIM(new_c.cccd) != '' AND new_c.cccd = old_c.cccd)
              OR
              (new_c.bhxh IS NOT NULL AND TRIM(new_c.bhxh) != '' AND new_c.bhxh = old_c.bhxh)
            )
      );

    -- 13.3. Chuẩn hóa các bản ghi cũ còn lại sang định dạng mới
    UPDATE public.customers c
    SET 
        customer_key = public.generate_customer_key(c.type, c.bhxh, c.cccd, c.name, c.phone),
        updated_at = NOW()
    WHERE (c.customer_key LIKE 'BHXH_%' OR c.customer_key LIKE 'BHYT_%')
      AND NOT EXISTS (
          SELECT 1 FROM public.customers exist_c
          WHERE exist_c.customer_key = public.generate_customer_key(c.type, c.bhxh, c.cccd, c.name, c.phone)
            AND exist_c.id != c.id
      );

    -- 13.4. Cập nhật lại liên kết customer_key và customer_id trên records
    UPDATE public.records r
    SET 
        customer_key = c.customer_key,
        customer_id = c.id
    FROM public.customers c
    WHERE (
        (c.cccd IS NOT NULL AND TRIM(c.cccd) != '' AND c.cccd = r.cccd)
        OR
        (c.bhxh IS NOT NULL AND TRIM(c.bhxh) != '' AND c.bhxh = r.bhxh)
    )
    AND (r.customer_key IS NULL OR r.customer_key != c.customer_key OR r.customer_id IS NULL OR r.customer_id != c.id);

    -- 11.5. Cập nhật dữ liệu kỳ đóng lịch sử sang from_month_date & to_month_date (Three-Tier Standard)
    UPDATE public.records
    SET 
        "from_month_date" = COALESCE("from_month_date", public.parse_month_str_to_date(COALESCE("from_month", "fromMonth"))),
        "fromMonthDate" = COALESCE("fromMonthDate", "from_month_date", public.parse_month_str_to_date(COALESCE("from_month", "fromMonth"))),
        "to_month_date" = COALESCE("to_month_date", public.parse_month_str_to_date(COALESCE("to_month", "toMonth"))),
        "toMonthDate" = COALESCE("toMonthDate", "to_month_date", public.parse_month_str_to_date(COALESCE("to_month", "toMonth"))),
        "submitted_date" = COALESCE("submitted_date", "submittedDate"),
        "decision_date" = COALESCE("decision_date", "decisionDate")
    WHERE ("from_month_date" IS NULL AND COALESCE("from_month", "fromMonth") IS NOT NULL)
       OR ("to_month_date" IS NULL AND COALESCE("to_month", "toMonth") IS NOT NULL)
       OR ("submitted_date" IS NULL AND "submittedDate" IS NOT NULL)
       OR ("decision_date" IS NULL AND "decisionDate" IS NOT NULL);

    PERFORM set_config('app.is_admin_override', 'false', true);
    PERFORM set_config('app.is_batch_import', 'false', true);
END $$;

