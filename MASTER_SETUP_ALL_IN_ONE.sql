-- 7.7. RPC Thống kê tài chính nâng cao (get_admin_finance_stats)
DROP FUNCTION IF EXISTS public.get_admin_finance_stats(text, text, text, text, text, text, text, text) CASCADE;
DROP FUNCTION IF EXISTS public.get_admin_finance_stats(text, text, text, text, text, text, text, text, text) CASCADE;
DROP FUNCTION IF EXISTS public.get_admin_finance_stats CASCADE;
CREATE OR REPLACE FUNCTION public.get_admin_finance_stats(
  filter_type text DEFAULT 'all',
  filter_staff text DEFAULT 'all',
  filter_period text DEFAULT 'all',
  start_date text DEFAULT '',
  end_date text DEFAULT '',
  search_txt text DEFAULT '',
  action_type_filter text DEFAULT 'all',
  payment_status_filter text DEFAULT 'all',
  filter_submitted text DEFAULT 'all'
) RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  total_revenue numeric;
  total_pending numeric;
  total_commission numeric;
BEGIN
  -- Tối ưu hóa: Thực hiện tính toán toàn bộ các chỉ số chỉ trong 1 lần quét (Single Pass Aggregation)
  SELECT 
    COALESCE(SUM(CASE WHEN r."paymentStatus" = 'Đã thu tiền' THEN r.amount ELSE 0 END), 0),
    COALESCE(SUM(CASE WHEN r."paymentStatus" = 'Chờ thanh toán' THEN r.amount ELSE 0 END), 0),
    COALESCE(SUM(
      CASE 
        WHEN r."paymentStatus" = 'Đã thu tiền' AND r.type = 'BHXH' AND (r."actionType" = 'Đăng ký mới' OR r."actionType" ILIKE '%mới%' OR r."actionType" = 'new') 
          THEN r.amount * (rates.comm_bhxh_new / 100.0)
        WHEN r."paymentStatus" = 'Đã thu tiền' AND r.type = 'BHXH' 
          THEN r.amount * (rates.comm_bhxh_renew / 100.0)
        WHEN r."paymentStatus" = 'Đã thu tiền' AND r.type = 'BHYT' AND (r."actionType" = 'Đăng ký mới' OR r."actionType" ILIKE '%mới%' OR r."actionType" = 'new') 
          THEN r.amount * (rates.comm_bhyt_new / 100.0)
        WHEN r."paymentStatus" = 'Đã thu tiền' AND r.type = 'BHYT' 
          THEN r.amount * (rates.comm_bhyt_renew / 100.0)
        ELSE 0
      END
    ), 0)
  INTO total_revenue, total_pending, total_commission
  FROM public.records r
  CROSS JOIN LATERAL public.get_commission_rates_for_date(public.safe_cast_date(r.date)) rates
  WHERE (
      (payment_status_filter = 'all' AND r."paymentStatus" IN ('Đã thu tiền', 'Chờ thanh toán'))
      OR (payment_status_filter = 'paid' AND r."paymentStatus" = 'Đã thu tiền')
      OR (payment_status_filter = 'pending' AND r."paymentStatus" = 'Chờ thanh toán')
      OR (r."paymentStatus" = payment_status_filter)
    )
    AND r."actionType" != 'Nhập từ Excel'
    AND (filter_type = 'all' OR r.type = filter_type)
    AND (filter_staff = 'all' OR r."staffId" = filter_staff)
    AND (action_type_filter = 'all' OR r."actionType" = action_type_filter)
    AND (search_txt = '' OR r.name ILIKE '%' || search_txt || '%' OR r.cccd ILIKE '%' || search_txt || '%' OR r.bhxh ILIKE '%' || search_txt || '%')
    AND (filter_period = 'all' OR start_date = '' OR end_date = '' OR (public.safe_cast_date(r.date) >= public.safe_cast_date(start_date) AND public.safe_cast_date(r.date) <= public.safe_cast_date(end_date)))
    AND (
      filter_submitted = 'all' 
      OR (filter_submitted = 'submitted' AND r."isSubmittedBHXH" = true)
      OR (filter_submitted = 'unsubmitted' AND (r."isSubmittedBHXH" = false OR r."isSubmittedBHXH" IS NULL))
      OR (filter_submitted LIKE 'batch_%' AND r."isSubmittedBHXH" = true AND r."submissionBatch" = SUBSTRING(filter_submitted FROM 7))
    );

  RETURN json_build_object(
    'totalRev', total_revenue,
    'totalPending', total_pending,
    'totalComm', total_commission
  );
END;
$$;

-- 8.8. RPC Xóa hồ sơ giao dịch an toàn (delete_record_safe)
DROP FUNCTION IF EXISTS public.delete_record_safe(BIGINT) CASCADE;
CREATE OR REPLACE FUNCTION public.delete_record_safe(p_record_id BIGINT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_rec RECORD;
  v_user_name TEXT;
  v_cust_key TEXT;
  v_remaining_records INT := 0;
  v_is_admin_user BOOLEAN := false;
  v_deleted_count INT := 0;
BEGIN
  v_is_admin_user := public.is_admin();

  SELECT id, name, type,
         COALESCE("isSubmittedBHXH", is_submitted_bhxh, false) AS is_submitted,
         COALESCE(payment_status, "paymentStatus") AS p_status,
         COALESCE(customer_key, "customerKey", public.generate_customer_key(type, bhxh, cccd, name, phone)) AS c_key,
         cccd, bhxh, phone
  INTO v_rec
  FROM public.records
  WHERE id = p_record_id;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('success', false, 'message', 'Không tìm thấy hồ sơ giao dịch #' || p_record_id);
  END IF;

  -- 1. Chặn nếu hồ sơ đã nộp cho cơ quan BHXH
  IF v_rec.is_submitted = true THEN
    RAISE EXCEPTION 'Hồ sơ "%" (Mã #%) ĐÃ ĐƯỢC CHUYỂN BHXH. Thao tác xóa bị từ chối!', v_rec.name, p_record_id
      USING ERRCODE = '23514';
  END IF;

  -- 2. Hồ sơ đã thu tiền: Chỉ Admin mới được xóa
  IF v_rec.p_status = 'Đã thu tiền' AND NOT v_is_admin_user THEN
    RAISE EXCEPTION 'Giao dịch #% của "%" đã thu tiền. Chỉ Quản lý/Admin mới có quyền xóa!', p_record_id, v_rec.name
      USING ERRCODE = '42501';
  END IF;

  -- 3. Tiến hành xóa hồ sơ giao dịch
  DELETE FROM public.records WHERE id = p_record_id;
  GET DIAGNOSTICS v_deleted_count = ROW_COUNT;

  IF v_deleted_count = 0 THEN
    DELETE FROM public.records WHERE id::text = p_record_id::text;
    GET DIAGNOSTICS v_deleted_count = ROW_COUNT;
  END IF;

  IF v_deleted_count = 0 THEN
    RETURN jsonb_build_object('success', false, 'message', 'Không thể xóa hồ sơ #' || p_record_id || ' từ CSDL (0 dòng bị ảnh hưởng).');
  END IF;

  -- 4. Đồng bộ bảng customers: Nếu khách hàng không còn giao dịch nào khác, tự động xóa luôn khách hàng
  v_cust_key := v_rec.c_key;
  IF v_cust_key IS NOT NULL AND TRIM(v_cust_key) != '' THEN
    SELECT COUNT(*) INTO v_remaining_records
    FROM public.records
    WHERE customer_key = v_cust_key 
       OR "customerKey" = v_cust_key
       OR (v_rec.cccd IS NOT NULL AND TRIM(v_rec.cccd) != '' AND cccd = v_rec.cccd)
       OR (v_rec.bhxh IS NOT NULL AND TRIM(v_rec.bhxh) != '' AND bhxh = v_rec.bhxh);

    IF v_remaining_records = 0 THEN
      DELETE FROM public.customers
      WHERE customer_key = v_cust_key 
         OR "customerKey" = v_cust_key
         OR (v_rec.cccd IS NOT NULL AND TRIM(v_rec.cccd) != '' AND cccd = v_rec.cccd)
         OR (v_rec.bhxh IS NOT NULL AND TRIM(v_rec.bhxh) != '' AND bhxh = v_rec.bhxh);
    END IF;
  END IF;

  -- 5. Ghi nhật ký kiểm toán an toàn
  v_user_name := COALESCE(auth.jwt() ->> 'name', auth.jwt() ->> 'email', 'Phạm Văn Học');
  BEGIN
    INSERT INTO public.auditlogs ("action", "details", "userId", "userName", "timestamp")
    VALUES (
      'Xóa giao dịch',
      'Đã xóa giao dịch #' || p_record_id || ' (' || COALESCE(v_rec.type, 'BHXH/BHYT') || ' - ' || COALESCE(v_rec.p_status, 'Chờ thanh toán') || ') của khách hàng ' || COALESCE(v_rec.name, ''),
      COALESCE(auth.uid()::TEXT, 'system'),
      v_user_name,
      NOW()
    );
  EXCEPTION WHEN OTHERS THEN
    NULL;
  END;

  RETURN jsonb_build_object('success', true, 'deleted_id', p_record_id, 'message', 'Đã xóa giao dịch thành công');
END;
$$;

