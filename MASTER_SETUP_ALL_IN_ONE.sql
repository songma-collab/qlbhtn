-- 6.2. Lấy IP Client an toàn (Chống giả mạo header)
CREATE OR REPLACE FUNCTION public.get_public_client_ip()
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_headers json;
  v_cf_ip text;
  v_cf_ray text;
  v_real_ip text;
  v_forwarded text;
  v_client_ip text := '127.0.0.1';
BEGIN
  BEGIN
    v_headers := current_setting('request.headers', true)::json;
    IF v_headers IS NOT NULL THEN
      v_cf_ip := TRIM(COALESCE(v_headers->>'cf-connecting-ip', ''));
      v_cf_ray := TRIM(COALESCE(v_headers->>'cf-ray', ''));
      v_real_ip := TRIM(COALESCE(v_headers->>'x-real-ip', ''));
      v_forwarded := TRIM(COALESCE(split_part(v_headers->>'x-forwarded-for', ',', 1), ''));

      -- Chỉ tin tưởng cf-connecting-ip khi request đi qua hạ tầng Cloudflare (có cf-ray)
      IF v_cf_ip != '' AND v_cf_ray != '' THEN
        v_client_ip := v_cf_ip;
      ELSIF v_real_ip != '' THEN
        v_client_ip := v_real_ip;
      ELSIF v_forwarded != '' THEN
        v_client_ip := v_forwarded;
      ELSE
        v_client_ip := '127.0.0.1';
      END IF;
    END IF;
  EXCEPTION WHEN OTHERS THEN
    v_client_ip := '127.0.0.1';
  END;
  RETURN TRIM(v_client_ip);
END;
$$;

-- 6.3. Cưỡng chế giới hạn tần suất (Rate Limit) theo IP
CREATE OR REPLACE FUNCTION public.enforce_public_rpc_rate_limit(
  p_action TEXT,
  p_max_calls INTEGER,
  p_window INTERVAL
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_ip text;
  v_count integer;
BEGIN
  IF auth.role() = 'authenticated' THEN
    RETURN;
  END IF;

  v_ip := public.get_public_client_ip();

  SELECT COUNT(*) INTO v_count
  FROM public.public_rpc_call_log
  WHERE action = p_action
    AND ip_address = v_ip
    AND called_at >= (NOW() - p_window);

  IF v_count >= p_max_calls THEN
    RAISE EXCEPTION 'RATE_LIMIT_EXCEEDED: Địa chỉ mạng (%) đã vượt giới hạn tra cứu cho phép. Vui lòng thử lại sau.', v_ip;
  END IF;

  INSERT INTO public.public_rpc_call_log (action, ip_address) VALUES (p_action, v_ip);
END;
$$;

REVOKE EXECUTE ON FUNCTION public.get_public_client_ip() FROM anon, public;
REVOKE EXECUTE ON FUNCTION public.enforce_public_rpc_rate_limit(TEXT, INTEGER, INTERVAL) FROM anon, public;

