-- 2.1. Bảng nhân sự cán bộ thu (staff)
CREATE TABLE IF NOT EXISTS public.staff (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT,
    role TEXT NOT NULL DEFAULT 'Nhân viên',
    status TEXT NOT NULL DEFAULT 'Đang hoạt động',
    area TEXT,
    staff_code TEXT,
    auth_user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    phone TEXT,
    cccd TEXT,
    username TEXT,
    permissions JSONB DEFAULT '[]'::jsonb,
    custom_permissions JSONB DEFAULT '[]'::jsonb,
    revoked_permissions JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2.2. Bảng đợt nộp hồ sơ cơ quan BHXH chính quy (submission_batches)
CREATE TABLE IF NOT EXISTS public.submission_batches (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    batch_code TEXT NOT NULL UNIQUE,
    insurance_type TEXT NOT NULL DEFAULT 'BHXH', -- 'BHXH', 'BHYT', 'CA_HAI'
    status TEXT NOT NULL DEFAULT 'draft',        -- 'draft', 'submitted', 'approved', 'rejected'
    created_by TEXT REFERENCES public.staff(id) ON DELETE SET NULL,
    total_records INT NOT NULL DEFAULT 0,
    total_amount NUMERIC NOT NULL DEFAULT 0,
    submission_date DATE,
    approval_date DATE,
    receipt_number TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2.3. Bảng thiết lập hệ thống (settings)
CREATE TABLE IF NOT EXISTS public.settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comm_bhxh_new NUMERIC DEFAULT 5,
    comm_bhxh_renew NUMERIC DEFAULT 3,
    comm_bhyt_new NUMERIC DEFAULT 5,
    comm_bhyt_renew NUMERIC DEFAULT 3,
    comm_bhxh NUMERIC DEFAULT 5,
    comm_bhyt NUMERIC DEFAULT 5,
    investment_rate NUMERIC DEFAULT 0.31,
    base_salary NUMERIC DEFAULT 2340000,
    poverty_standard NUMERIC DEFAULT 1500000,
    cpi_index JSONB,
    agency_name TEXT DEFAULT 'Đại lý thu BHXH Sông Mã',
    agency_code TEXT DEFAULT 'VSS-SM-001',
    bank_bin TEXT DEFAULT '970422',
    bank_id TEXT DEFAULT 'MB',
