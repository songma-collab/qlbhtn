-- Khóa ngoại ngược từ customers sang records (latest_record_id)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_customers_latest_record'
    ) THEN
        ALTER TABLE public.customers 
        ADD CONSTRAINT fk_customers_latest_record 
        FOREIGN KEY (latest_record_id) REFERENCES public.records(id) ON DELETE SET NULL;
    END IF;
END $$;

