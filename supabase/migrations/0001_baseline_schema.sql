-- 4.2. View Lịch sử Giao dịch Khách hàng (v_customer_transactions)
DROP VIEW IF EXISTS public.v_customer_transactions CASCADE;
CREATE OR REPLACE VIEW public.v_customer_transactions 
WITH (security_invoker = true) AS
SELECT 
    r.id AS transaction_id,
    r.date AS transaction_date,
    r.type AS service_type,
    r.action_type,
    r.months AS duration_months,
    r.from_month,
    r.to_month,
    r.amount AS transaction_amount,
    r.payment_status,
    r.staff_id,
    r.is_submitted_bhxh,
    r.submission_batch,
    r.submission_batch_id,
    r.notes AS transaction_notes,
    c.id AS customer_id,
    c.customer_key,
    c.name AS customer_name,
    c.cccd AS customer_cccd,
    c.bhxh AS customer_bhxh,
    c.phone AS customer_phone,
    c.address AS customer_address,
    c.dob AS customer_dob,
    c.gender AS customer_gender,
    c.total_contributions,
    c.total_amount_paid,
    c.next_payment
FROM public.records r
LEFT JOIN public.customers c ON (r.customer_id = c.id OR r.customer_key = c.customer_key)
ORDER BY r.date DESC;

